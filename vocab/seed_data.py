def seed_database(db) -> int:
    """Populates the database with initial curated decks if empty."""
    added_count = 0
    existing_groups = {g.name.lower(): g for g in db.get_groups()}

    for group_data in SEED_GROUPS:
        name = group_data["name"]
        if name.lower() in existing_groups:
            group = existing_groups[name.lower()]
            group_id = group.id
        else:
            group_id = db.create_group(
                name=name,
                description=group_data.get("description", ""),
                color=group_data.get("color", "cyan")
            )

        # Check existing words in this group to avoid duplicates
        existing_words = {w.word.lower() for w in db.get_words(group_id=group_id, limit=500)}
        for w in group_data["words"]:
            if w["word"].lower() not in existing_words:
                db.add_word(
                    group_id=group_id,
                    word=w["word"],
                    definition=w["definition"],
                    phonetic=w.get("phonetic", ""),
                    pos=w.get("pos", ""),
                    example=w.get("example", ""),
                    mnemonic=w.get("mnemonic", ""),
                    tags=w.get("tags", "")
                )
                added_count += 1

    return added_count
